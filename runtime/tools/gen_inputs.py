#!/usr/bin/env python3
"""Turn the oracle's printed inputs (corpus/e2e_increment.txt) and the mainnet network
settings (vendor/network/mainnet_settings.xdr) into Lean literals: Proofs/IncrementInputs.lean."""
import base64, re, os
root = os.path.join(os.path.dirname(__file__), '..') + '/'
settings = base64.b64decode(open(root + 'vendor/network/mainnet_settings.xdr').read().strip())
lines = open(root + 'corpus/e2e_increment.txt').read().split('\n')

def ba(h):
    return 'ByteArray.mk #[' + ', '.join(str(x) for x in bytes.fromhex(h)) + ']'

out = ['/-', 'Inputs of the oracle runs in corpus/e2e_increment.txt and the mainnet network',
       'settings (vendor/network/mainnet_settings.xdr, fetched 2026-10-25), as Lean literals.',
       'Generated by tools/gen_inputs.py.', '-/', 'import SorobanLean.Host.E2EFinish',
       'import SorobanLean.Host.Network', '', 'namespace Proofs', 'open Soroban', '',
       'set_option maxRecDepth 100000 in',
       f'def mainnetSettings : ByteArray := ByteArray.mk #[{", ".join(str(x) for x in settings)}]', '']
for tag in ['call0', 'call1', 'call2']:
    hf = res = src = li = None
    ents = []
    for l in lines:
        w = l.split(' ')
        if len(w) < 3 or w[0] != tag or w[1] != 'input':
            continue
        if w[2] == 'host_fn': hf = w[3]
        elif w[2] == 'resources': res = w[3]
        elif w[2] == 'source': src = w[3]
        elif w[2] == 'entry':
            e = None if w[3] == '-' else w[3]
            ttl = re.match(r'ttl=Some\((\d+)\)', w[4]); rs = re.match(r'rent_size=Some\((\d+)\)', w[5])
            tm = (f'some {{ liveUntilLedger := {ttl.group(1)}, entrySizeForRent := {rs.group(1)} }}'
                  if ttl and rs else 'none')
            ents.append(f'({("some (" + ba(e) + ")") if e else "none"}, {tm})')
        elif w[2] == 'ledger':
            kv = dict(x.split('=') for x in w[3:])
            li = (f'{{ protocolVersion := {kv["proto"]}, sequenceNumber := {kv["seq"]}, timestamp := {kv["ts"]}, '
                  f'networkId := {ba(kv["nid"])}, baseReserve := {kv["reserve"]}, minTempEntryTtl := {kv["min_temp"]}, '
                  f'minPersistentEntryTtl := {kv["min_pers"]}, maxEntryTtl := {kv["max_ttl"]} }}')
    out.append('set_option maxRecDepth 100000 in')
    out.append(f'def {tag}Input : E2EInput :=\n  {{ hostFn := {ba(hf)},\n    resources := {ba(res)},\n'
               f'    sourceAccount := {ba(src)},\n    ledgerInfo := {li},\n    ledgerEntries := #[{", ".join(ents)}],\n'
               f'    basePrngSeed := ByteArray.mk (Array.replicate 32 0) }}\n')
    for l in lines:
        w = l.split(' ')
        if len(w) >= 5 and w[0] == tag and w[1] == 'output' and w[2] == 'result' and w[3] == 'ok':
            out.append(f'def {tag}Result : ByteArray := {ba(w[4])}\n')
out.append('end Proofs')
open(root + 'Proofs/IncrementInputs.lean', 'w').write('\n'.join(out) + '\n')
