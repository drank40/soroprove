#!/usr/bin/env python3
"""Generate Proofs/IncrementConcrete.lean: one kernel-checked theorem per observable output
of each oracle run in corpus/e2e_increment.txt."""
import re, os
root = os.path.join(os.path.dirname(__file__), '..') + '/'
lines = open(root + 'corpus/e2e_increment.txt').read().split('\n')
def ba(h): return '[' + ', '.join(str(x) for x in bytes.fromhex(h)) + ']'
out = ['/-', 'Kernel-checked end-to-end facts about the real increment contract: for each oracle run,',
       '`invoke_host_function` (Lean model) produces exactly the outputs the real host produced',
       '(corpus/e2e_increment.txt): encoded result, every ledger change, CPU instructions and peak',
       'memory, all by kernel evaluation (`decide +kernel`) from the raw input bytes.',
       'Generated by tools/gen_concrete_proofs.py.', '-/',
       'import Proofs.Common', '', 'namespace Proofs', 'open Soroban', '', 'set_option maxRecDepth 200000', '',
       '/-- A ledger change in the oracle\'s printed form. -/',
       'structure ChangeSummary where',
       '  readOnly : Bool',
       '  key : List UInt8',
       '  oldSize : Nat',
       '  newValue : Option (List UInt8)',
       '  newSize : Nat',
       '  ttl : Option (Nat × Nat)',
       '  deriving DecidableEq', '',
       'def changesSummary (inp : E2EInput) : List ChangeSummary :=',
       '  match (runE2E inp).1 with',
       '  | .ok r => r.ledgerChanges.toList.map fun c =>',
       '      { readOnly := c.readOnly, key := c.encodedKey.data.toList, oldSize := c.oldEntrySizeBytesForRent,',
       '        newValue := c.encodedNewValue.map (·.data.toList), newSize := c.newEntrySizeBytesForRent,',
       '        ttl := c.ttlChange.map fun t => (t.oldLiveUntilLedger, t.newLiveUntilLedger) }',
       '  | .error _ => []', '']
pat = re.compile(r'^(\w+) output change ro=(\w+) key=(\w+) old_size=(\d+) new=(\S+) new_size=(\d+) ttl=(.*)$')
for tag in ['call0', 'call1', 'call2']:
    ch = []; cpu = mem = None
    for l in lines:
        m = pat.match(l)
        if m and m.group(1) == tag:
            ro, key, osz, nv, nsz, ttl = m.groups()[1:]
            t = re.match(r'Some\(\((\d+), (\d+)\)\)', ttl)
            ttls = f'some ({t.group(1)}, {t.group(2)})' if t else 'none'
            nvs = 'none' if nv == '-' else f'some ({ba(nv)})'
            ch.append(f'⟨{ro}, {ba(key)}, {osz}, {nvs}, {nsz}, {ttls}⟩')
        w = l.split(' ')
        if len(w) >= 5 and w[0] == tag and w[1] == 'output' and w[2] == 'budget':
            cpu = w[3].split('=')[1]; mem = w[4].split('=')[1]
    out.append(f'theorem {tag}_result : resultBytes? {tag}Input = some {tag}Result := by decide +kernel')
    out.append(f'theorem {tag}_cpu : cpuConsumed {tag}Input = {cpu} := by decide +kernel')
    out.append(f'theorem {tag}_mem : memConsumed {tag}Input = {mem} := by decide +kernel')
    out.append('set_option maxRecDepth 100000 in')
    out.append(f'def {tag}ExpectedChanges : List ChangeSummary :=\n  [{", ".join(ch)}]')
    out.append(f'theorem {tag}_changes : changesSummary {tag}Input = {tag}ExpectedChanges := by decide +kernel')
    out.append('')
out.append('end Proofs')
open(root + 'Proofs/IncrementConcrete.lean', 'w').write('\n'.join(out) + '\n')
