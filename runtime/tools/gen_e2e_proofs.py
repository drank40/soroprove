#!/usr/bin/env python3
"""Generate kernel-checked end-to-end facts for recorded oracle runs.

usage: gen_e2e_proofs.py <corpus transcript> <Module prefix> <tag>...
writes Proofs/<Prefix>Inputs.lean (inputs as literals) and Proofs/<Prefix>Concrete.lean
(one theorem per observable output: result, ledger changes, events, cpu, peak mem)."""
import re, sys, os
root = os.path.join(os.path.dirname(__file__), '..') + '/'
path, prefix, tags = sys.argv[1], sys.argv[2], sys.argv[3:]
lines = open(root + path).read().split('\n')
def ba(h): return 'ByteArray.mk #[' + ', '.join(str(x) for x in bytes.fromhex(h)) + ']'
def bl(h): return '[' + ', '.join(str(x) for x in bytes.fromhex(h)) + ']'
ns = f'Proofs.{prefix}'
inp = ['/-', f'Inputs of the oracle runs in {path} as Lean literals.', 'Generated by tools/gen_e2e_proofs.py.', '-/',
       'import Proofs.Common', '', f'namespace {ns}', 'open Soroban', '']
thm = ['/-', f'Kernel-checked end-to-end facts for the oracle runs in {path}: the Lean model of',
       '`invoke_host_function` produces exactly the real host\'s outputs (encoded result, ledger',
       'changes, contract events, CPU instructions, peak memory) from the raw input bytes.',
       'Generated by tools/gen_e2e_proofs.py.', '-/', f'import Proofs.{prefix}Inputs', '', f'namespace {ns}', 'open Soroban Proofs', '',
       'set_option maxRecDepth 200000', '',
       '/-- A ledger change in the oracle\'s printed form. -/', 'structure ChangeSummary where', '  readOnly : Bool',
       '  key : List UInt8', '  oldSize : Nat', '  newValue : Option (List UInt8)', '  newSize : Nat', '  ttl : Option (Nat × Nat)',
       '  deriving DecidableEq', '', 'def changesSummary (inp : E2EInput) : List ChangeSummary :=', '  match (runE2E inp).1 with',
       '  | .ok r => r.ledgerChanges.toList.map fun c =>',
       '      { readOnly := c.readOnly, key := c.encodedKey.data.toList, oldSize := c.oldEntrySizeBytesForRent,',
       '        newValue := c.encodedNewValue.map (·.data.toList), newSize := c.newEntrySizeBytesForRent,',
       '        ttl := c.ttlChange.map fun t => (t.oldLiveUntilLedger, t.newLiveUntilLedger) }', '  | .error _ => []', '',
       'def eventsBytes (inp : E2EInput) : List (List UInt8) :=', '  match (runE2E inp).1 with',
       '  | .ok r => r.encodedContractEvents.toList.map (·.data.toList)', '  | .error _ => []', '',
       '/-- The error value of a failed invocation (payload of the host `Error`). -/',
       'def resultError? (inp : E2EInput) : Option UInt64 :=', '  match (runE2E inp).1 with',
       '  | .ok r => match r.result with | .error e => some e.payload | .ok _ => none', '  | .error _ => none', '']
pat = re.compile(r'^(\w+) output change ro=(\w+) key=(\w+) old_size=(\d+) new=(\S+) new_size=(\d+) ttl=(.*)$')
etys = ["Contract","WasmVm","Context","Storage","Object","Crypto","Events","Budget","Value","Auth"]
ecodes = ["ArithDomain","IndexBounds","InvalidInput","MissingValue","ExistingValue","ExceededLimit","InvalidAction","InternalError","UnexpectedType","UnexpectedSize"]
for tag in tags:
    hf = res = src = li = None; ents = []; auths = []
    res_ok = res_err = None; ch = []; evs = []; cpu = mem = None
    for l in lines:
        w = l.split(' ')
        if len(w) < 3 or w[0] != tag: continue
        if w[1] == 'input':
            if w[2] == 'host_fn': hf = w[3]
            elif w[2] == 'resources': res = w[3]
            elif w[2] == 'source': src = w[3]
            elif w[2] == 'auth': auths.append(ba(w[3]))
            elif w[2] == 'entry':
                e = None if w[3] == '-' else w[3]
                ttl = re.match(r'ttl=Some\((\d+)\)', w[4]); rs = re.match(r'rent_size=Some\((\d+)\)', w[5])
                tm = f'some {{ liveUntilLedger := {ttl.group(1)}, entrySizeForRent := {rs.group(1)} }}' if ttl and rs else 'none'
                ents.append(f'({("some (" + ba(e) + ")") if e else "none"}, {tm})')
            elif w[2] == 'ledger':
                kv = dict(x.split('=') for x in w[3:])
                li = (f'{{ protocolVersion := {kv["proto"]}, sequenceNumber := {kv["seq"]}, timestamp := {kv["ts"]}, '
                      f'networkId := {ba(kv["nid"])}, baseReserve := {kv["reserve"]}, minTempEntryTtl := {kv["min_temp"]}, '
                      f'minPersistentEntryTtl := {kv["min_pers"]}, maxEntryTtl := {kv["max_ttl"]} }}')
        elif w[1] == 'output':
            m = pat.match(l)
            if m:
                ro, key, osz, nv, nsz, ttl = m.groups()[1:]
                t = re.match(r'Some\(\((\d+), (\d+)\)\)', ttl)
                ch.append(f'⟨{ro}, {bl(key)}, {osz}, {"none" if nv == "-" else "some " + bl(nv)}, {nsz}, {"some (" + t.group(1) + ", " + t.group(2) + ")" if t else "none"}⟩')
            elif w[2] == 'result' and w[3] == 'ok': res_ok = w[4]
            elif w[2] == 'result' and w[3] == 'err':
                m2 = re.match(r'Error\((\w+), (\w+)\)', ' '.join(w[4:]))
                ty = etys.index(m2.group(1)); co = ecodes.index(m2.group(2))
                res_err = (co << 32) | (ty << 8) | 3
            elif w[2] == 'event': evs.append(bl(w[3]))
            elif w[2] == 'budget': cpu = w[3].split('=')[1]; mem = w[4].split('=')[1]
    inp.append('set_option maxRecDepth 100000 in')
    inp.append(f'def {tag}Input : E2EInput :=\n  {{ hostFn := {ba(hf)},\n    resources := {ba(res)},\n    sourceAccount := {ba(src)},\n'
               f'    authEntries := #[{", ".join(auths)}],\n    ledgerInfo := {li},\n    ledgerEntries := #[{", ".join(ents)}],\n'
               f'    basePrngSeed := ByteArray.mk (Array.replicate 32 0) }}\n')
    if res_ok: thm.append(f'theorem {tag}_result : resultBytes? {tag}Input = some {ba(res_ok)} := by decide +kernel')
    if res_err is not None: thm.append(f'theorem {tag}_error : resultError? {tag}Input = some {res_err} := by decide +kernel')
    thm.append(f'theorem {tag}_cpu : cpuConsumed {tag}Input = {cpu} := by decide +kernel')
    thm.append(f'theorem {tag}_mem : memConsumed {tag}Input = {mem} := by decide +kernel')
    thm.append('set_option maxRecDepth 100000 in')
    thm.append(f'def {tag}ExpectedChanges : List ChangeSummary :=\n  [{", ".join(ch)}]')
    thm.append(f'theorem {tag}_changes : changesSummary {tag}Input = {tag}ExpectedChanges := by decide +kernel')
    thm.append('set_option maxRecDepth 100000 in')
    thm.append(f'def {tag}ExpectedEvents : List (List UInt8) :=\n  [{", ".join(evs)}]')
    thm.append(f'theorem {tag}_events : eventsBytes {tag}Input = {tag}ExpectedEvents := by decide +kernel')
    thm.append('')
inp.append(f'end {ns}'); thm.append(f'end {ns}')
open(root + f'Proofs/{prefix}Inputs.lean', 'w').write('\n'.join(inp) + '\n')
open(root + f'Proofs/{prefix}Concrete.lean', 'w').write('\n'.join(thm) + '\n')
