pub const PRELUDE: &str = r#"//! Generated by ponytail-mir: the ABI as the wasm sees it, then the lifted
//! functions. rustc's type checker is the verifier for this file.
#![no_std]
#![allow(unused, non_snake_case, non_camel_case_types, non_upper_case_globals, unreachable_code, unused_unsafe, bindings_with_variant_name)]

/// A Soroban `Val`: 64 bits, tag in the low byte. Never an integer.
#[repr(transparent)]
#[derive(Clone, Copy)]
pub struct Val(pub u64);

/// `StorageType` is not a `Val`: it crosses the host boundary as a plain u64.
#[repr(u64)]
#[derive(Clone, Copy)]
pub enum StorageType { Temporary = 0, Persistent = 1, Instance = 2 }

extern "C" {
    /// wasm `unreachable`: the host traps.
    pub fn trap() -> !;
    /// Bottom: a value the model does not carry. Never a literal.
    pub fn unknown() -> Val;
    pub fn unknown_i64() -> u64;
}
"#;

/// LLVM name -> Rust identifier: the part after the module dot for host and
/// runtime functions, the whole name for `llvm.*` intrinsics.
pub fn rs_name(llvm: &str) -> String {
    match llvm {
        "ponytail.unknown" => return "unknown".into(),
        "ponytail.unknown.i64" => return "unknown_i64".into(),
        "soroban.trap" => return "trap".into(),
        _ => {}
    }
    let base = if llvm.starts_with("llvm.") { llvm } else { llvm.rsplit('.').next().unwrap_or(llvm) };
    let mut o: String = base.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if o.starts_with(|c: char| c.is_ascii_digit()) || !o.chars().any(|c| c.is_ascii_alphanumeric()) {
        o.insert(0, 't');
    }
    // Keywords, and the primitive types a helper called f32 would shadow.
    const TAKEN: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl",
        "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct",
        "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "gen", "try",
        "f16", "f32", "f64", "f128", "i8", "i16", "i32", "i64", "i128", "u8", "u16", "u32", "u64", "u128", "bool",
        "usize", "isize", "str", "char",
    ];
    if TAKEN.contains(&o.as_str()) {
        o.push('_');
    }
    o
}

pub fn rs_ty(t: BasicTypeEnum) -> Result<&'static str, String> {
    Ok(match t {
        BasicTypeEnum::IntType(i) => match i.get_bit_width() {
            1 => "bool",
            8 => "u8",
            16 => "u16",
            32 => "u32",
            64 => "u64",
            w => return Err(format!("i{w} has no Rust type here")),
        },
        BasicTypeEnum::StructType(s) if s.get_name().map(|n| n.to_bytes() == b"Val").unwrap_or(false) => "Val",
        BasicTypeEnum::PointerType(_) => "*mut u8",
        other => return Err(format!("no Rust type for {other:?}")),
    })
}

fn sig(f: FunctionValue) -> Result<(Vec<String>, String), String> {
    // A host function's `soroban.sig` says which i64 is really a StorageType.
    let storage: Vec<bool> = f
        .get_string_attribute(AttributeLoc::Function, "soroban.sig")
        .and_then(|a| a.get_string_value().to_str().ok().map(|s| s.to_owned()))
        .map(|s| {
            let inside = s.trim_start_matches('(').split(')').next().unwrap_or("");
            inside.split(',').map(|p| p.trim() == "StorageType").collect()
        })
        .unwrap_or_default();
    let params = f
        .get_params()
        .iter()
        .enumerate()
        .map(|(i, p)| {
            let t = if storage.get(i).copied().unwrap_or(false) { "StorageType" } else { rs_ty(p.get_type())? };
            Ok(format!("a{i}: {t}"))
        })
        .collect::<Result<Vec<_>, String>>()?;
    let ret = match f.get_type().get_return_type() {
        None => String::new(),
        Some(t) => format!(" -> {}", rs_ty(t)?),
    };
    Ok((params, ret))
}

/// The stub crate's header: types, externs, statics. Shared by the stub and
/// by the Rust output, which appends the lifted bodies to it.
pub fn header(m: &Module) -> Result<String, String> {
    let mut s = String::from(PRELUDE);
    let mut g = m.get_first_global();
    while let Some(gv) = g {
        g = gv.get_next_global();
        let init = gv.get_initializer().and_then(|v| v.into_int_value().get_zero_extended_constant()).unwrap_or(0);
        let _ = writeln!(s, "pub static mut {}: u64 = {init};", gv.get_name().to_string_lossy().to_uppercase());
    }
    let mut ext = String::new();
    for f in m.get_functions() {
        let name = f.get_name().to_string_lossy().into_owned();
        if f.count_basic_blocks() > 0
            || name.starts_with("llvm.lifetime")
            || name == "llvm.assume"
            || name.starts_with("soroban.val.")
            || name.starts_with("ponytail.")
            || matches!(name.as_str(), "soroban.storage_type" | "soroban.trap")
        {
            continue;
        }
        let (params, ret) = sig(f)?;
        if let Some(a) = f.get_string_attribute(AttributeLoc::Function, "soroban.import") {
            let _ = writeln!(ext, "    /// wasm import `{}`", a.get_string_value().to_string_lossy());
        }
        let _ = writeln!(ext, "    pub fn {}({}){ret};", rs_name(&name), params.join(", "));
    }
    if !ext.is_empty() {
        let _ = write!(s, "\nextern \"C\" {{\n{ext}}}\n");
    }
    Ok(s)
}

/// One empty function per defined LLVM function, so the TyCtxt has a DefId
/// and a signature for each body ponytail-mir is about to build.
fn stubs(m: &Module) -> Result<String, String> {
    let mut s = String::new();
    for f in m.get_functions() {
        if f.count_basic_blocks() == 0 {
            continue;
        }
        let (params, ret) = sig(f)?;
        let vis = if f.get_linkage() == Linkage::Internal { "" } else { "pub " };
        let _ = writeln!(s, "{vis}fn {}({}){ret} {{ loop {{}} }}", rs_name(&f.get_name().to_string_lossy()), params.join(", "));
    }
    Ok(s)
}

fn load<'ctx>(ctx: &'ctx Context, path: &PathBuf) -> Result<Module<'ctx>, String> {
    let buf = MemoryBuffer::create_from_file(path).map_err(|e| e.to_string())?;
    ctx.create_module_from_ir(buf).map_err(|e| e.to_string())
}

struct Lift {
    ll: PathBuf,
    rust: bool,
    validate: bool,
}

impl Callbacks for Lift {
    fn after_analysis<'tcx>(&mut self, _c: &Compiler, tcx: TyCtxt<'tcx>) -> Compilation {
        let ctx = Context::create();
        let m = load(&ctx, &self.ll).unwrap_or_else(|e| fatal(&e));
        let env = mir::Env::new(tcx);
        let mut bodies = Vec::new();
        for f in m.get_functions() {
            if f.count_basic_blocks() == 0 {
                continue;
            }
            let name = rs_name(&f.get_name().to_string_lossy());
            let Some(&def_id) = env.fns.get(&name) else { fatal(&format!("no stub for {name}")) };
            match mir::build(&env, f, def_id) {
                Ok(mut body) => {
                    if self.validate {
                        // rustc's own MIR validator and cleanup passes, the
                        // ones every real body goes through.
                        body.phase = MirPhase::Analysis(AnalysisPhase::Initial);
                        rustc_mir_transform::run_analysis_to_runtime_passes(tcx, &mut body);
                    }
                    bodies.push(body);
                }
                Err(e) => eprintln!("ponytail-mir: {name}: {e}"),
            }
        }
        let mut out = std::io::stdout().lock();
        if self.rust {
            let head = header(&m).unwrap_or_else(|e| fatal(&e));
            let text = rs::emit(tcx, &env, &head, &bodies).unwrap_or_else(|e| fatal(&e));
            std::io::Write::write_all(&mut out, text.as_bytes()).expect("write");
        } else {
            for body in &bodies {
                let d = MirDumper::new(tcx, "ponytail", body).expect("-Zdump-mir=ponytail is passed");
                d.dump_mir_to_writer(body, &mut out).expect("write MIR");
                std::io::Write::write_all(&mut out, b"\n").expect("write");
            }
        }
        Compilation::Stop
    }
}

fn fatal(msg: &str) -> ! {
    eprintln!("ponytail-mir: {msg}");
    std::process::exit(1)
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let ll = args.get(1).filter(|a| !a.starts_with("--")).cloned().unwrap_or_else(|| {
        eprintln!("usage: ponytail-mir <contract.inline.ll> [--rust] [--no-validate]");
        std::process::exit(2)
    });
    let rust = args.iter().any(|a| a == "--rust");
    let validate = !args.iter().any(|a| a == "--no-validate");
    let ll = PathBuf::from(ll);

    // The stub crate rustc compiles to give us a TyCtxt with our items in it.
    let stub = {
        let ctx = Context::create();
        let m = load(&ctx, &ll).unwrap_or_else(|e| fatal(&e));
        format!("{}\n{}", header(&m).unwrap_or_else(|e| fatal(&e)), stubs(&m).unwrap_or_else(|e| fatal(&e)))
    };
    let stub_path = std::env::temp_dir().join(format!("ponytail-stub-{}.rs", std::process::id()));
    std::fs::write(&stub_path, stub).unwrap_or_else(|e| fatal(&e.to_string()));

    let mut rustc_args = vec![
        args[0].clone(),
        stub_path.to_string_lossy().into_owned(),
        "--crate-type=lib".into(),
        "--edition=2021".into(),
        "--crate-name=contract".into(),
        // Gates MirDumper; the printer behind -Zdump-mir.
        "-Zdump-mir=ponytail".into(),
        format!("--sysroot={}", sysroot()),
    ];
    if validate {
        rustc_args.push("-Zvalidate-mir".into());
    }
    rustc_driver::run_compiler(&rustc_args, &mut Lift { ll, rust, validate });
    let _ = std::fs::remove_file(stub_path);
}

/// The sysroot of the toolchain this binary was built with; rustc_driver
/// cannot find it from a binary that does not live in the toolchain.
fn sysroot() -> String {
    if let Ok(s) = std::env::var("SYSROOT") {
        return s;
    }
    let out = std::process::Command::new("rustc")
        .env("RUSTUP_TOOLCHAIN", option_env!("RUSTUP_TOOLCHAIN").unwrap_or("nightly-2026-05-01"))
        .args(["--print", "sysroot"])
        .output()
        .expect("rustc --print sysroot");
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}
