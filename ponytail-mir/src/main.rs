//! wasm -> (ponytail-wasm --inline) LLVM IR -> MIR -> Rust.
//!
//! The MIR is real: `rustc_middle::mir::Body` values built inside a `TyCtxt`,
//! typed with rustc's own `Ty`s for `Val`, `StorageType`, the host functions
//! and the wasm globals; one basic block per LLVM block, phis as edge copies.
//! rustc prints it (the `-Zdump-mir` printer) and checks it (`-Zvalidate-mir`
//! through the analysis-to-runtime pipeline). The Rust is then emitted from
//! that MIR, structured with rustc's dominators and reverse postorder over the
//! body. Nothing runs backwards: no Rust is written before the MIR exists.
//!
//! The `TyCtxt` comes from compiling a stub crate generated from the `.ll`'s
//! own declarations: the two ABI types, one `extern "C"` per host function
//! and intrinsic, one static per wasm global, and one empty `fn` per defined
//! function so every body has a `DefId` with the right signature.
