//! LLVM IR -> Rust. One typed `let` per SSA value, one `match` arm per basic
//! block when there is more than one, one typed `extern "C"` declaration per
//! host function. Nothing is invented: this is the inlined IR in another
//! syntax, and rustc's type checker is the second verifier after
//! `module.verify()`. `ponytail-mir` then asks rustc for the MIR.
use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;

use inkwell::basic_block::BasicBlock;
use inkwell::module::{Linkage, Module};
use inkwell::types::BasicTypeEnum;
use inkwell::values::{
    AnyValue, AnyValueEnum, AsValueRef, BasicValue, BasicValueEnum, CallSiteValue, FunctionValue, InstructionOpcode,
    InstructionValue, Operand, PhiValue,
};
use inkwell::IntPredicate;

use crate::{const_addr, storage_name, VT, HOST_FNS};

const PRELUDE: &str = r#"//! Generated by `ponytail-wasm --rust`: the inlined LLVM IR in Rust syntax.
//! One `let` per SSA value, one `match` arm per basic block. rustc's type
//! checker is the verifier here, and `ponytail-mir` asks it for the MIR.
#![no_std]
#![allow(unused, non_snake_case, non_camel_case_types, non_upper_case_globals, unreachable_code, unused_unsafe, bindings_with_variant_name)]

/// A Soroban `Val`: 64 bits, tag in the low byte. Never an integer.
#[repr(transparent)]
#[derive(Clone, Copy)]
pub struct Val(pub u64);
impl Val {
    pub const fn from_payload(p: u64) -> Val { Val(p) }
    pub const fn payload(self) -> u64 { self.0 }
}

/// `StorageType` is not a `Val`: it crosses the host boundary as a plain u64.
#[repr(u64)]
#[derive(Clone, Copy)]
pub enum StorageType { Temporary = 0, Persistent = 1, Instance = 2 }

extern "C" {
    /// wasm `unreachable`: the host traps.
    pub fn trap() -> !;
    /// Bottom: a value the model does not carry. Never a literal.
    pub fn unknown() -> Val;
    pub fn unknown_i64() -> u64;
    /// A StorageType the model could not resolve to a variant.
    pub fn storage_type(x: u64) -> StorageType;
}

"#;

type R<T> = Result<T, String>;

pub fn emit(m: &Module) -> R<String> {
    let mut out = String::from(PRELUDE);
    // wasm globals: the stack pointer, mostly.
    let mut g = m.get_first_global();
    while let Some(gv) = g {
        g = gv.get_next_global();
        let name = gv.get_name().to_string_lossy().to_uppercase();
        let init = gv
            .get_initializer()
            .and_then(|v| v.into_int_value().get_zero_extended_constant())
            .unwrap_or(0);
        let _ = writeln!(out, "pub static mut {name}: u64 = {init};");
    }
    let mut ext = String::new();
    for f in m.get_functions() {
        if f.count_basic_blocks() > 0 {
            continue;
        }
        let name = f.get_name().to_string_lossy().into_owned();
        if name.starts_with("llvm.")
            || name.starts_with("soroban.val.")
            || name.starts_with("ponytail.")
            || matches!(name.as_str(), "soroban.storage_type" | "soroban.trap")
        {
            continue; // the prelude covers these
        }
        if let Some(h) = HOST_FNS.iter().find(|h| h.name == name) {
            let ps: Vec<String> = h.args.iter().enumerate().map(|(i, a)| format!("a{i}: {}", vt_ty(*a))).collect();
            let _ = writeln!(ext, "    /// wasm import `{}.{}`", h.module, h.code);
            let _ = writeln!(ext, "    pub fn {}({}) -> {};", fn_name(&name), ps.join(", "), vt_ty(h.ret));
        } else {
            let ps: Vec<String> = f
                .get_params()
                .iter()
                .enumerate()
                .map(|(i, p)| Ok(format!("a{i}: {}", ty(p.get_type())?)))
                .collect::<R<_>>()?;
            let _ = writeln!(ext, "    pub fn {}({}){};", fn_name(&name), ps.join(", "), ret_ty(f)?);
        }
    }
    if !ext.is_empty() {
        let _ = write!(out, "\nextern \"C\" {{\n{ext}}}\n");
    }
    // A value must not shadow a function it might be named after: LLVM named
    // the result of `put_contract_data` after its callee, and Rust resolves a
    // later `put_contract_data(..)` to that local.
    let mut reserved: HashSet<String> =
        ["Val", "StorageType", "trap", "unknown", "unknown_i64", "storage_type"].iter().map(|s| s.to_string()).collect();
    reserved.extend(m.get_functions().map(|f| fn_name(&f.get_name().to_string_lossy())));
    for f in m.get_functions() {
        if f.count_basic_blocks() > 0 {
            out.push('\n');
            out.push_str(&emit_fn(f, &reserved)?);
        }
    }
    Ok(out)
}

fn vt_ty(v: VT) -> &'static str {
    match v {
        VT::Val => "Val",
        VT::Raw64 => "u64",
        VT::Storage => "StorageType",
    }
}

fn ty(t: BasicTypeEnum) -> R<String> {
    Ok(match t {
        BasicTypeEnum::IntType(i) => match i.get_bit_width() {
            1 => "bool",
            8 => "u8",
            16 => "u16",
            32 => "u32",
            64 => "u64",
            w => return Err(format!("i{w} has no Rust type here")),
        }
        .into(),
        BasicTypeEnum::StructType(s) if s.get_name().map(|n| n.to_bytes() == b"Val").unwrap_or(false) => "Val".into(),
        BasicTypeEnum::PointerType(_) => "*mut u8".into(),
        other => return Err(format!("no Rust type for {other:?}")),
    })
}

fn signed(t: &str) -> &'static str {
    match t {
        "u8" => "i8",
        "u16" => "i16",
        "u32" => "i32",
        _ => "i64",
    }
}

fn zero(t: &str) -> &'static str {
    match t {
        "bool" => "false",
        "Val" => "Val(0)",
        "StorageType" => "StorageType::Temporary",
        "*mut u8" => "core::ptr::null_mut()",
        _ => "0",
    }
}

fn ret_ty(f: FunctionValue) -> R<String> {
    Ok(match f.get_type().get_return_type() {
        None => String::new(),
        Some(t) => format!(" -> {}", ty(t)?),
    })
}

/// `ledger.put_contract_data` -> `put_contract_data`; anything else as is.
fn fn_name(llvm: &str) -> String {
    ident_raw(llvm.rsplit('.').next().unwrap_or(llvm))
}

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct", "super", "trait",
    "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do",
    "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

fn ident_raw(s: &str) -> String {
    let mut o: String = s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if o.starts_with(|c: char| c.is_ascii_digit()) || !o.chars().any(|c| c.is_ascii_alphanumeric()) {
        o.insert(0, 't');
    }
    if KEYWORDS.contains(&o.as_str()) {
        o.push('_');
    }
    o
}

fn bits(t: &str) -> u32 {
    match t {
        "bool" => 1,
        "u8" => 8,
        "u16" => 16,
        "u32" => 32,
        _ => 64,
    }
}

fn key(v: impl AsValueRef) -> usize {
    v.as_value_ref() as usize
}

fn insts(bb: BasicBlock) -> Vec<InstructionValue> {
    let mut v = Vec::new();
    let mut cur = bb.get_first_instruction();
    while let Some(i) = cur {
        v.push(i);
        cur = i.get_next_instruction();
    }
    v
}

struct Fn_<'ctx> {
    names: HashMap<usize, String>,
    hoisted: HashSet<usize>,
    blocks: HashMap<usize, usize>,
    ret: Option<BasicTypeEnum<'ctx>>,
}

impl<'ctx> Fn_<'ctx> {
    /// A fresh identifier from an LLVM name, or `t<n>` for an unnamed value.
    fn name(&mut self, raw: &str, n: usize, used: &mut HashSet<String>) -> String {
        let mut id = if raw.is_empty() { format!("t{n}") } else { ident_raw(raw) };
        if !used.insert(id.clone()) {
            id = format!("{id}_{n}");
            used.insert(id.clone());
        }
        id
    }

    /// The Rust type of a value: its LLVM type, except a StorageType, which
    /// the IR carries as i64 and Rust as the enum.
    fn vty(&self, i: InstructionValue<'ctx>) -> R<String> {
        if let Ok(cs) = CallSiteValue::try_from(i) {
            if cs.get_called_fn_value().map(|f| f.get_name().to_bytes() == b"soroban.storage_type").unwrap_or(false) {
                return Ok("StorageType".into());
            }
        }
        ty(BasicTypeEnum::try_from(i.get_type()).map_err(|_| "void")?)
    }

    /// Is operand `k` of `i` the result of a `soroban.storage_type` call?
    fn is_storage_call(&self, i: InstructionValue<'ctx>, k: u32) -> bool {
        let Some(Operand::Value(v)) = i.get_operand(k) else { return false };
        v.as_instruction_value().map(|d| self.vty(d).ok() == Some("StorageType".into())).unwrap_or(false)
    }

    fn val(&self, v: BasicValueEnum<'ctx>) -> R<String> {
        if let Some(n) = self.names.get(&key(v)) {
            return Ok(n.clone());
        }
        match v {
            BasicValueEnum::IntValue(i) if i.is_constant_int() => {
                let w = i.get_type().get_bit_width();
                let z = i.get_zero_extended_constant().unwrap_or(0);
                let s = i.get_sign_extended_constant().unwrap_or(0);
                Ok(match w {
                    1 => (z != 0).to_string(),
                    // A small negative reads better than its two's complement.
                    _ if s < 0 && s > -(1 << 32) => format!("({s}i{w} as u{w})"),
                    _ => format!("{z}u{w}"),
                })
            }
            BasicValueEnum::IntValue(i) if i.is_undef() => Ok(format!("{} /* undef */", zero(&ty(v.get_type())?))),
            BasicValueEnum::PointerValue(p) if p.is_null() => Ok("core::ptr::null_mut()".into()),
            BasicValueEnum::PointerValue(p) if p.is_const() => match const_addr(p) {
                Some(a) => Ok(format!("({a}u64 as usize as *mut u8)")),
                None => {
                    // A global's address.
                    let n = p.get_name().to_string_lossy();
                    if n.is_empty() {
                        return Err("unsupported constant pointer".into());
                    }
                    Ok(format!("(&raw mut {} as *mut u8)", n.to_uppercase()))
                }
            },
            BasicValueEnum::StructValue(s) if s.is_const() => Ok(match s.get_field_at_index(0) {
                Some(BasicValueEnum::IntValue(i)) if i.is_constant_int() => {
                    format!("Val({})", i.get_zero_extended_constant().unwrap_or(0))
                }
                // zeroinitializer, undef or poison: LLVM's "any value". The
                // comment says the program did not choose this one.
                _ => "Val(0) /* undef */".into(),
            }),
            other => Err(format!("unsupported operand {}", other.print_to_string())),
        }
    }

    fn op(&self, i: InstructionValue<'ctx>, k: u32) -> R<String> {
        match i.get_operand(k) {
            Some(Operand::Value(v)) => self.val(v),
            _ => Err(format!("operand {k} of {} is not a value", i.print_to_string())),
        }
    }

    fn block(&self, i: InstructionValue<'ctx>, k: u32) -> R<usize> {
        match i.get_operand(k) {
            Some(Operand::Block(b)) => self.blocks.get(&(b.as_mut_ptr() as usize)).copied().ok_or_else(|| "unknown block".into()),
            _ => Err("operand is not a block".into()),
        }
    }

    fn opty(&self, i: InstructionValue<'ctx>, k: u32) -> R<String> {
        match i.get_operand(k) {
            Some(Operand::Value(v)) => ty(v.get_type()),
            _ => Err("operand is not a value".into()),
        }
    }

    /// The expression an instruction computes, or None for one that emits
    /// nothing (phi, lifetime markers, alloca handled at the top).
    fn expr(&self, i: InstructionValue<'ctx>) -> R<Option<String>> {
        use InstructionOpcode::*;
        let t = || ty(BasicTypeEnum::try_from(i.get_type()).map_err(|_| "void")?);
        let a = |k| self.op(i, k);
        let bin = |f: &str| -> R<Option<String>> { Ok(Some(format!("{}.{f}({})", a(0)?, a(1)?))) };
        let sbin = |o: &str| -> R<Option<String>> {
            let (t, s) = (t()?, signed(&t()?));
            Ok(Some(format!("(({} as {s}) {o} ({} as {s})) as {t}", a(0)?, a(1)?)))
        };
        Ok(match i.get_opcode() {
            Phi | Alloca => None,
            Load => Some(format!("core::ptr::read_unaligned({} as *const {})", a(0)?, t()?)),
            Store => Some(format!("core::ptr::write_unaligned({} as *mut {}, {})", a(1)?, self.opty(i, 0)?, a(0)?)),
            GetElementPtr => {
                if i.get_num_operands() != 2 {
                    return Err(format!("gep shape: {}", i.print_to_string()));
                }
                Some(format!("{}.wrapping_offset({} as i64 as isize)", a(0)?, a(1)?))
            }
            Add => bin("wrapping_add")?,
            Sub => bin("wrapping_sub")?,
            Mul => bin("wrapping_mul")?,
            UDiv => Some(format!("{} / {}", a(0)?, a(1)?)),
            URem => Some(format!("{} % {}", a(0)?, a(1)?)),
            SDiv => sbin("/")?,
            SRem => sbin("%")?,
            And => Some(format!("{} & {}", a(0)?, a(1)?)),
            Or => Some(format!("{} | {}", a(0)?, a(1)?)),
            Xor => Some(format!("{} ^ {}", a(0)?, a(1)?)),
            Shl => Some(format!("{}.wrapping_shl({} as u32)", a(0)?, a(1)?)),
            LShr => Some(format!("{}.wrapping_shr({} as u32)", a(0)?, a(1)?)),
            AShr => {
                let t = t()?;
                Some(format!("(({} as {}).wrapping_shr({} as u32)) as {t}", a(0)?, signed(&t), a(1)?))
            }
            ICmp => {
                let p = i.get_icmp_predicate().ok_or("icmp without predicate")?;
                let st = signed(&self.opty(i, 0)?);
                let (x, y) = (a(0)?, a(1)?);
                let s = |o: &str| format!("({x} as {st}) {o} ({y} as {st})");
                Some(match p {
                    IntPredicate::EQ => format!("{x} == {y}"),
                    IntPredicate::NE => format!("{x} != {y}"),
                    IntPredicate::UGT => format!("{x} > {y}"),
                    IntPredicate::UGE => format!("{x} >= {y}"),
                    IntPredicate::ULT => format!("{x} < {y}"),
                    IntPredicate::ULE => format!("{x} <= {y}"),
                    IntPredicate::SGT => s(">"),
                    IntPredicate::SGE => s(">="),
                    IntPredicate::SLT => s("<"),
                    IntPredicate::SLE => s("<="),
                })
            }
            Select => Some(format!("if {} {{ {} }} else {{ {} }}", a(0)?, a(1)?, a(2)?)),
            ZExt | Trunc | PtrToInt | IntToPtr | BitCast => {
                let t = t()?;
                Some(match (i.get_opcode(), t.as_str()) {
                    (Trunc, "bool") => format!("({} & 1) != 0", a(0)?),
                    (PtrToInt, _) => format!("{} as usize as {t}", a(0)?),
                    (IntToPtr, _) => format!("{} as usize as *mut u8", a(0)?),
                    (BitCast, _) => a(0)?,
                    _ => format!("{} as {t}", a(0)?),
                })
            }
            SExt => {
                let (t, from) = (t()?, self.opty(i, 0)?);
                Some(if from == "bool" {
                    format!("if {} {{ !0{t} }} else {{ 0{t} }}", a(0)?)
                } else {
                    format!("{} as {} as {} as {t}", a(0)?, signed(&from), signed(&t))
                })
            }
            Freeze => Some(a(0)?),
            Call => {
                let cs = CallSiteValue::try_from(i).map_err(|_| "call")?;
                let callee = cs.get_called_fn_value().ok_or("indirect call")?;
                let name = callee.get_name().to_string_lossy().into_owned();
                let args: Vec<String> = (0..cs.count_arguments()).map(|k| self.op(i, k)).collect::<R<_>>()?;
                let w = t().map(|t| bits(&t)).unwrap_or(64);
                let st = t().map(|t| signed(&t).to_string()).unwrap_or_default();
                match name.as_str() {
                    n if n.starts_with("llvm.lifetime") || n == "llvm.assume" => None,
                    n if n.starts_with("llvm.memset.") => {
                        Some(format!("core::ptr::write_bytes({}, {} as u8, {} as usize)", args[0], args[1], args[2]))
                    }
                    n if n.starts_with("llvm.memcpy.") || n.starts_with("llvm.memmove.") => {
                        Some(format!("core::ptr::copy({}, {}, {} as usize)", args[1], args[0], args[2]))
                    }
                    n if n.starts_with("llvm.bswap.") => Some(format!("{}.swap_bytes()", args[0])),
                    n if n.starts_with("llvm.ctlz.") => Some(format!("{}.leading_zeros() as {}", args[0], t()?)),
                    n if n.starts_with("llvm.cttz.") => Some(format!("{}.trailing_zeros() as {}", args[0], t()?)),
                    n if n.starts_with("llvm.ctpop.") => Some(format!("{}.count_ones() as {}", args[0], t()?)),
                    n if n.starts_with("llvm.fshl.") => Some(format!(
                        "{{ let s = {c} % {w}; if s == 0 {{ {a} }} else {{ ({a} << s) | ({b} >> ({w} - s)) }} }}",
                        a = args[0], b = args[1], c = args[2]
                    )),
                    n if n.starts_with("llvm.fshr.") => Some(format!(
                        "{{ let s = {c} % {w}; if s == 0 {{ {b} }} else {{ ({a} << ({w} - s)) | ({b} >> s) }} }}",
                        a = args[0], b = args[1], c = args[2]
                    )),
                    n if n.starts_with("llvm.umax.") => Some(format!("core::cmp::max({}, {})", args[0], args[1])),
                    n if n.starts_with("llvm.umin.") => Some(format!("core::cmp::min({}, {})", args[0], args[1])),
                    n if n.starts_with("llvm.smax.") => {
                        Some(format!("core::cmp::max({} as {st}, {} as {st}) as {}", args[0], args[1], t()?))
                    }
                    n if n.starts_with("llvm.smin.") => {
                        Some(format!("core::cmp::min({} as {st}, {} as {st}) as {}", args[0], args[1], t()?))
                    }
                    n if n.starts_with("llvm.abs.") => Some(format!("({} as {st}).wrapping_abs() as {}", args[0], t()?)),
                    n if n.starts_with("llvm.uadd.sat.") => Some(format!("{}.saturating_add({})", args[0], args[1])),
                    n if n.starts_with("llvm.usub.sat.") => Some(format!("{}.saturating_sub({})", args[0], args[1])),
                    n if n.starts_with("llvm.expect.") => Some(args[0].clone()),
                    n if n.starts_with("llvm.") => return Err(format!("intrinsic {n}")),
                    "soroban.trap" => Some("trap()".into()),
                    "ponytail.unknown" => Some("unknown()".into()),
                    "ponytail.unknown.i64" => Some("unknown_i64()".into()),
                    "soroban.val.from_payload" => Some(format!("Val::from_payload({})", args[0])),
                    "soroban.val.payload" => Some(format!("{}.payload()", args[0])),
                    "soroban.storage_type" => {
                        let lit = i.get_operand(0).and_then(|o| match o {
                            Operand::Value(BasicValueEnum::IntValue(v)) if v.is_constant_int() => v.get_zero_extended_constant(),
                            _ => None,
                        });
                        Some(match lit {
                            Some(c @ 0..=2) => format!("StorageType::{}", storage_name(c as i64)),
                            _ => format!("storage_type({})", args[0]),
                        })
                    }
                    _ => {
                        // A StorageType position fed by a plain integer -- a
                        // phi of two variants after LLVM merged two paths --
                        // goes through the converter, so Rust sees the enum.
                        let args: Vec<String> = match HOST_FNS.iter().find(|h| h.name == name) {
                            Some(h) => args
                                .into_iter()
                                .enumerate()
                                .map(|(k, a)| {
                                    let plain_int = h.args.get(k) == Some(&VT::Storage)
                                        && self.opty(i, k as u32).map(|t| t != "StorageType").unwrap_or(true)
                                        && !self.is_storage_call(i, k as u32);
                                    if plain_int { format!("storage_type({a})") } else { a }
                                })
                                .collect(),
                            None => args,
                        };
                        Some(format!("{}({})", fn_name(&name), args.join(", ")))
                    }
                }
            }
            Unreachable | Br | Switch | Return => return Err("terminator".into()),
            op => return Err(format!("unsupported instruction {op:?}: {}", i.print_to_string())),
        })
    }

    /// Phi moves for an edge into `to`, as parallel copies.
    fn phis(&self, to: BasicBlock<'ctx>, from: BasicBlock<'ctx>, ind: &str) -> R<String> {
        let mut moves = Vec::new();
        for i in insts(to) {
            let Ok(phi) = PhiValue::try_from(i) else { break };
            for k in 0..phi.count_incoming() {
                let Some((v, b)) = phi.get_incoming(k) else { continue };
                if b == from {
                    moves.push((self.names[&key(i)].clone(), self.val(v)?));
                }
            }
        }
        let mut s = String::new();
        for (n, (_, e)) in moves.iter().enumerate() {
            let _ = writeln!(s, "{ind}let __p{n} = {e};");
        }
        for (n, (dst, _)) in moves.iter().enumerate() {
            let _ = writeln!(s, "{ind}{dst} = __p{n};");
        }
        Ok(s)
    }

    fn jump(&self, from: BasicBlock<'ctx>, i: InstructionValue<'ctx>, k: u32, ind: &str) -> R<String> {
        let Some(Operand::Block(to)) = i.get_operand(k) else { return Err("branch target".into()) };
        Ok(format!("{}{ind}__bb = {};\n", self.phis(to, from, ind)?, self.block(i, k)?))
    }

    fn terminator(&self, bb: BasicBlock<'ctx>, i: InstructionValue<'ctx>, ind: &str, single: bool) -> R<String> {
        use InstructionOpcode::*;
        Ok(match i.get_opcode() {
            Return => match (self.ret, i.get_num_operands()) {
                (Some(_), 1) => format!("{ind}return {};\n", self.op(i, 0)?),
                _ => format!("{ind}return;\n"),
            },
            Unreachable => format!("{ind}unreachable!();\n"),
            _ if single => return Err(format!("branch in a single-block function: {}", i.print_to_string())),
            // LLVM stores a conditional branch as [cond, false, true].
            Br if i.get_num_operands() == 3 => format!(
                "{ind}if {} {{\n{}{ind}}} else {{\n{}{ind}}}\n{ind}continue;\n",
                self.op(i, 0)?,
                self.jump(bb, i, 2, &format!("{ind}    "))?,
                self.jump(bb, i, 1, &format!("{ind}    "))?
            ),
            Br => format!("{}{ind}continue;\n", self.jump(bb, i, 0, ind)?),
            Switch => {
                let mut s = format!("{ind}match {} {{\n", self.op(i, 0)?);
                let ind2 = format!("{ind}        ");
                let mut k = 2;
                while k + 1 < i.get_num_operands() {
                    let _ = write!(s, "{ind}    {} => {{\n{}{ind}    }}\n", self.op(i, k)?, self.jump(bb, i, k + 1, &ind2)?);
                    k += 2;
                }
                let _ = write!(s, "{ind}    _ => {{\n{}{ind}    }}\n{ind}}}\n{ind}continue;\n", self.jump(bb, i, 1, &ind2)?);
                s
            }
            op => return Err(format!("unsupported terminator {op:?}")),
        })
    }
}

fn uses_outside(i: InstructionValue, bb: BasicBlock) -> bool {
    let mut u = i.get_first_use();
    while let Some(x) = u {
        // inkwell classifies a user by its type: an `add` comes back as an
        // IntValue, only a void instruction as an InstructionValue.
        let user = match x.get_user() {
            AnyValueEnum::InstructionValue(ui) => Some(ui),
            other => BasicValueEnum::try_from(other).ok().and_then(|v| v.as_instruction_value()),
        };
        match user.and_then(|ui| PhiValue::try_from(ui).ok()) {
            // A phi reads its operand in the incoming block, where the move
            // is emitted -- not where the phi itself sits.
            Some(phi) => {
                for k in 0..phi.count_incoming() {
                    if let Some((v, from)) = phi.get_incoming(k) {
                        if key(v) == key(i) && from != bb {
                            return true;
                        }
                    }
                }
            }
            None if user.and_then(|ui| ui.get_parent()) != Some(bb) => return true,
            None => {}
        }
        u = x.get_next_use();
    }
    false
}

fn emit_fn(f: FunctionValue, reserved: &HashSet<String>) -> R<String> {
    let fname = fn_name(&f.get_name().to_string_lossy());
    let vis = if f.get_linkage() == Linkage::Internal { "" } else { "pub " };
    let blocks = f.get_basic_blocks();
    let mut fx = Fn_ {
        names: HashMap::new(),
        hoisted: HashSet::new(),
        blocks: blocks.iter().enumerate().map(|(n, b)| (b.as_mut_ptr() as usize, n)).collect(),
        ret: f.get_type().get_return_type(),
    };
    let mut used = reserved.clone();
    let mut params = Vec::new();
    for (n, p) in f.get_params().iter().enumerate() {
        let id = fx.name(&p.get_name().to_string_lossy(), n, &mut used);
        fx.names.insert(key(*p), id.clone());
        params.push(format!("{id}: {}", ty(p.get_type())?));
    }
    let single = blocks.len() == 1;
    // Name every value; decide which live across blocks (or are phis) and
    // must be declared up front; allocas become arrays declared up front.
    let mut top = String::new();
    let mut n = 0;
    for bb in &blocks {
        for i in insts(*bb) {
            if BasicTypeEnum::try_from(i.get_type()).is_err() {
                continue; // void
            }
            let id = fx.name(&i.get_name().map(|c| c.to_string_lossy().into_owned()).unwrap_or_default(), n, &mut used);
            n += 1;
            fx.names.insert(key(i), id.clone());
            if i.get_opcode() == InstructionOpcode::Alloca {
                let size = match i.get_allocated_type() {
                    Ok(BasicTypeEnum::ArrayType(a)) => a.len() as u64,
                    Ok(BasicTypeEnum::IntType(t)) => (t.get_bit_width() / 8) as u64,
                    _ => return Err("alloca shape".into()),
                };
                let _ = writeln!(top, "        let mut {id}_buf: [u8; {size}] = [0; {size}];");
                let _ = writeln!(top, "        let {id}: *mut u8 = {id}_buf.as_mut_ptr();");
                fx.hoisted.insert(key(i));
            } else if !single && (i.get_opcode() == InstructionOpcode::Phi || uses_outside(i, *bb)) {
                let t = fx.vty(i)?;
                // Assigned on every path before it is read; the initialiser
                // only satisfies definite-initialisation.
                let _ = writeln!(top, "        let mut {id}: {t} = {};", zero(&t));
                fx.hoisted.insert(key(i));
            }
        }
    }
    let mut body = top;
    let emit_block = |fx: &Fn_, bb: BasicBlock, ind: &str| -> R<String> {
        let mut s = String::new();
        for i in insts(bb) {
            if i.get_opcode() == InstructionOpcode::Alloca {
                continue;
            }
            if i.is_terminator() {
                s.push_str(&fx.terminator(bb, i, ind, single)?);
                continue;
            }
            let Some(e) = fx.expr(i)? else { continue };
            match BasicTypeEnum::try_from(i.get_type()) {
                Err(_) => {
                    let _ = writeln!(s, "{ind}{e};");
                }
                Ok(_) => {
                    let id = &fx.names[&key(i)];
                    if fx.hoisted.contains(&key(i)) {
                        let _ = writeln!(s, "{ind}{id} = {e};");
                    } else {
                        let _ = writeln!(s, "{ind}let {id}: {} = {e};", fx.vty(i)?);
                    }
                }
            }
        }
        Ok(s)
    };
    if single {
        body.push_str(&emit_block(&fx, blocks[0], "        ")?);
    } else {
        body.push_str("        let mut __bb: u32 = 0;\n        loop {\n            match __bb {\n");
        for (n, bb) in blocks.iter().enumerate() {
            let _ = writeln!(body, "                {n} => {{ // {}", bb.get_name().to_string_lossy());
            body.push_str(&emit_block(&fx, *bb, "                    ")?);
            body.push_str("                }\n");
        }
        body.push_str("                _ => unreachable!(),\n            }\n        }\n");
    }
    Ok(format!("{vis}fn {fname}({}){} {{\n    unsafe {{\n{body}    }}\n}}\n", params.join(", "), ret_ty(f)?))
}
