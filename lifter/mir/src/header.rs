/// LLVM name -> Rust identifier: the part after the module dot for host and
/// runtime functions, the whole name for `llvm.*` intrinsics.
pub fn rs_name(llvm: &str) -> String {
    match llvm {
        "diver.unknown" => return "unknown".into(),
        "diver.unknown.i64" => return "unknown_i64".into(),
        "soroban.trap" => return "trap".into(),
        _ => {}
    }
    let base = if llvm.starts_with("llvm.") { llvm } else { llvm.rsplit('.').next().unwrap_or(llvm) };
    let mut o: String = base.chars().map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if o.starts_with(|c: char| c.is_ascii_digit()) || !o.chars().any(|c| c.is_ascii_alphanumeric()) {
        o.insert(0, 't');
    }
    // Keywords, and the primitive types a helper called f32 would shadow.
    const TAKEN: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl",
        "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static", "struct",
        "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "gen", "try",
        "f16", "f32", "f64", "f128", "i8", "i16", "i32", "i64", "i128", "u8", "u16", "u32", "u64", "u128", "bool",
        "usize", "isize", "str", "char",
    ];
    if TAKEN.contains(&o.as_str()) {
        o.push('_');
    }
    o
}

pub fn rs_ty(t: BasicTypeEnum) -> Result<&'static str, String> {
    Ok(match t {
        BasicTypeEnum::IntType(i) => match i.get_bit_width() {
            1 => "bool",
            8 => "u8",
            16 => "u16",
            32 => "u32",
            64 => "u64",
            w => return Err(format!("i{w} has no Rust type here")),
        },
        BasicTypeEnum::StructType(s) if s.get_name().map(|n| n.to_bytes() == b"Val").unwrap_or(false) => "Val",
        // LLVM's `*.with.overflow` intrinsics return an anonymous `{ iN, i1 }`
        // (result, overflow-bit); model it as the Rust tuple `(uN, bool)`.
        BasicTypeEnum::StructType(s) if overflow_pair_width(s).is_some() => match overflow_pair_width(s).unwrap() {
            8 => "(u8, bool)",
            16 => "(u16, bool)",
            32 => "(u32, bool)",
            64 => "(u64, bool)",
            _ => "(u128, bool)",
        },
        BasicTypeEnum::PointerType(_) => "*mut u8",
        other => return Err(format!("no Rust type for {other:?}")),
    })
}

/// If `s` is an `{ iN, i1 }` overflow pair, return N; else None.
pub fn overflow_pair_width(s: inkwell::types::StructType) -> Option<u32> {
    let f = s.get_field_types();
    if f.len() != 2 {
        return None;
    }
    let (BasicTypeEnum::IntType(a), BasicTypeEnum::IntType(b)) = (f[0], f[1]) else { return None };
    if b.get_bit_width() != 1 {
        return None;
    }
    matches!(a.get_bit_width(), 8 | 16 | 32 | 64 | 128).then(|| a.get_bit_width())
}

pub(crate) fn pty_str(t: infer::PTy) -> &'static str {
    match t {
        infer::PTy::Int => "u64",
        infer::PTy::Ptr => "*mut u8",
        infer::PTy::Val => "Val",
        infer::PTy::Storage => "StorageType",
    }
}

/// A function's Rust signature. A host function's comes from its
/// `soroban.sig`; a lifted function's from `infer`; anything else from the
/// LLVM types.
pub(crate) fn sig(f: FunctionValue, sigs: &infer::Sigs) -> Result<(Vec<String>, String), String> {
    let name = f.get_name().to_string_lossy().into_owned();
    let storage: Vec<bool> = f
        .get_string_attribute(AttributeLoc::Function, "soroban.sig")
        .and_then(|a| a.get_string_value().to_str().ok().map(|s| s.to_owned()))
        .map(|s| {
            let inside = s.trim_start_matches('(').split(')').next().unwrap_or("");
            inside.split(',').map(|p| p.trim() == "StorageType").collect()
        })
        .unwrap_or_default();
    let params = f
        .get_params()
        .iter()
        .enumerate()
        .map(|(i, p)| {
            let t = match sigs.param(&name, i) {
                Some(k) => pty_str(k),
                None if storage.get(i).copied().unwrap_or(false) => "StorageType",
                None => rs_ty(p.get_type())?,
            };
            Ok(format!("a{i}: {t}"))
        })
        .collect::<Result<Vec<_>, String>>()?;
    let ret = if mir::noreturn(f) {
        " -> !".into()
    } else {
        match (f.get_type().get_return_type(), sigs.ret(&name)) {
            (None, _) => String::new(),
            (Some(_), Some(k)) => format!(" -> {}", pty_str(k)),
            (Some(t), None) => format!(" -> {}", rs_ty(t)?),
        }
    };
    Ok((params, ret))
}

/// The `contractspecv0` lines stellar-diver attached as named metadata.
pub fn spec_lines(m: &Module) -> Vec<String> {
    meta_lines(m, "soroban.spec")
}

/// `name demangled::path` for every function the fingerprints named.
pub fn sdk_names(m: &Module) -> Vec<String> {
    m.get_functions()
        .filter_map(|f| {
            let a = f.get_string_attribute(AttributeLoc::Function, "sdk.name")?;
            Some(format!("{} {}", rs_name(&f.get_name().to_string_lossy()), a.get_string_value().to_string_lossy()))
        })
        .collect()
}

pub fn meta_lines(m: &Module, key: &str) -> Vec<String> {
    m.get_global_metadata(key)
        .iter()
        .filter_map(|n| match n.get_node_values()?.first()? {
            inkwell::values::BasicMetadataValueEnum::MetadataValue(s) => {
                s.get_string_value().map(|b| String::from_utf8_lossy(b).into_owned())
            }
            _ => None,
        })
        .collect()
}

/// The stub crate's header: types, externs, statics, and the declared ABI as
/// a comment. Shared by the stub and by the Rust output, which appends the
/// lifted bodies to it.
pub fn header(m: &Module, sigs: &infer::Sigs) -> Result<String, String> {
    let mut s = String::from(PRELUDE);
    let spec = spec_lines(m);
    if !spec.is_empty() {
        s.push_str("\n// contractspecv0, the ABI the contract declares. ScVal shapes, not memory layout.\n");
        for l in &spec {
            let _ = writeln!(s, "//   {l}");
        }
    }
    let mut g = m.get_first_global();
    while let Some(gv) = g {
        g = gv.get_next_global();
        if gv.as_pointer_value().get_first_use().is_none() {
            continue; // the stack pointer, once every frame is an alloca
        }
        // The function table is LLVM's own; the Rust calls through it are direct or dropped.
        let Some(init) = gv.get_initializer().filter(|v| v.is_int_value()) else { continue };
        let init = init.into_int_value().get_zero_extended_constant().unwrap_or(0);
        let _ = writeln!(s, "pub static mut {}: u64 = {init};", gv.get_name().to_string_lossy().to_uppercase());
    }
    let mut ext = String::new();
    let mut imported: Vec<String> = Vec::new();
    for f in m.get_functions() {
        let name = f.get_name().to_string_lossy().into_owned();
        if f.count_basic_blocks() > 0
            || f.as_global_value().as_pointer_value().get_first_use().is_none()
            || name.starts_with("llvm.lifetime")
            || name == "llvm.assume"
            || name.starts_with("soroban.val.")
            || name.starts_with("diver.")
            || matches!(name.as_str(), "soroban.storage_type" | "soroban.trap")
        {
            continue;
        }
        let (params, ret) = sig(f, sigs)?;
        if let Some(a) = f.get_string_attribute(AttributeLoc::Function, "soroban.import") {
            let _ = writeln!(ext, "    /// wasm import `{}`", a.get_string_value().to_string_lossy());
        }
        let _ = writeln!(ext, "    pub fn {}({}){ret};", rs_name(&name), params.join(", "));
        imported.push(rs_name(&name));
    }
    if !ext.is_empty() {
        let _ = write!(s, "\nextern \"C\" {{\n{ext}}}\n");
    }
    let ctors: String = CONSTRUCTORS.iter().filter(|(i, _)| imported.iter().any(|x| x == i)).map(|(_, c)| *c).collect();
    if !ctors.is_empty() {
        let _ = write!(s, "\n/// The SDK constructors the imports above implement, their data as literals: the host reads the same bytes.\nimpl Val {{\n{ctors}}}\n");
    }
    Ok(s)
}

/// One empty function per defined LLVM function, so the TyCtxt has a DefId
/// and a signature for each body stellar-diver-mir is about to build.
pub(crate) fn stubs(m: &Module, sigs: &infer::Sigs) -> Result<String, String> {
    let mut s = String::new();
    for f in m.get_functions() {
        if f.count_basic_blocks() == 0 {
            continue;
        }
        let (params, ret) = sig(f, sigs)?;
        let vis = if f.get_linkage() == Linkage::Internal { "" } else { "pub " };
        let _ = writeln!(s, "{vis}fn {}({}){ret} {{ loop {{}} }}", rs_name(&f.get_name().to_string_lossy()), params.join(", "));
    }
    Ok(s)
}
