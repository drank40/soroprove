#!/usr/bin/env python3
"""Generate SorobanLean/Env/HostFns.lean from the pinned env.json.

Mirrors the checks soroban-env-macros applies when it builds the x-macro
(src: vendor/rs-soroban-env/soroban-env-macros/src/call_macro_with_all_host_functions.rs:14-71):
per-module function export names must follow the sequence
"_", "0".."9", "a".."z", "A".."Z", then 2-char products, and "mod.fn"
export pairs must be unique. Ordering of HOST_FUNCTIONS (and therefore of
`HostFn.all`) is env.json order, modules first then functions
(src: soroban-env-host/src/vm/func_info.rs:96-140).
"""
import hashlib
import itertools
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / "vendor/rs-soroban-env/soroban-env-common/env.json"
OUT = ROOT / "SorobanLean/Env/HostFns.lean"

LEAN_KEYWORDS = {"end", "fun", "let", "in", "do", "if", "then", "else", "match", "with",
                 "at", "by", "have", "show", "from", "where", "open", "import", "def",
                 "theorem", "structure", "inductive", "class", "instance", "namespace",
                 "section", "variable", "universe", "for", "return", "mut", "try", "catch"}


def ident(name: str) -> str:
    return f"«{name}»" if name in LEAN_KEYWORDS else name


def lean_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def expected_exports():
    chars = ["_"] + [chr(c) for c in range(ord("0"), ord("9") + 1)] + \
        [chr(c) for c in range(ord("a"), ord("z") + 1)] + [chr(c) for c in range(ord("A"), ord("Z") + 1)]
    return chars + [a + b for a, b in itertools.product(chars, chars)]


def main():
    raw = ENV.read_bytes()
    env = json.loads(raw)
    sha = hashlib.sha256(raw).hexdigest()
    exp = expected_exports()
    seen = {}
    fns = []
    types = set()
    for m in env["modules"]:
        if len(m["functions"]) > len(exp):
            sys.exit(f"too many functions in module {m['name']}")
        for f, want in zip(m["functions"], exp):
            if f["export"] != want:
                sys.exit(f"unexpected export name {m['name']}.{f['name']}: {f['export']} != {want}")
            key = f"{m['export']}.{f['export']}"
            if key in seen:
                sys.exit(f"duplicate export {key}")
            seen[key] = f"{m['name']}.{f['name']}"
            fns.append((m, f))
            types.add(f["return"])
            for a in f["args"]:
                types.add(a["type"])
    names = [f["name"] for _, f in fns]
    assert len(set(names)) == len(names), "host fn names must be globally unique"
    types = sorted(types)

    o = []
    w = o.append
    w("-- GENERATED by tools/gen_env.py from vendor/rs-soroban-env/soroban-env-common/env.json")
    w(f"-- env.json sha256: {sha}")
    w("-- rs-soroban-env v30.0.0 @ 0c99950. DO NOT EDIT.")
    w("")
    w("namespace Soroban.Env")
    w("")
    w("/-- Every type that appears in a host function signature in env.json. -/")
    w("inductive ValTy where")
    for t in types:
        w(f"  | {ident(t)}")
    w("  deriving DecidableEq, Repr, Inhabited")
    w("")
    w("/-- All ValTy constructors in declaration order. -/")
    w("def ValTy.all : List ValTy := [" + ", ".join("." + ident(t) for t in types) + "]")
    w("")
    w("/-- The env.json modules, in file order. -/")
    w("inductive Module where")
    for m in env["modules"]:
        w(f"  | {ident(m['name'])}")
    w("  deriving DecidableEq, Repr, Inhabited")
    w("")
    w("/-- Wasm import-module string of each env module (`export` in env.json). -/")
    w("def Module.exportName : Module → String")
    for m in env["modules"]:
        w(f"  | .{ident(m['name'])} => {lean_str(m['export'])}")
    w("")
    w("/-- All host functions, one constructor per env.json entry. -/")
    w("inductive HostFn where")
    for m, f in fns:
        w(f"  /-- {m['name']}.{f['name']}: {f.get('docs', '').strip().replace('-/', '- /')} -/")
        w(f"  | {ident(f['name'])}")
    w("  deriving DecidableEq, Repr, Inhabited")
    w("")
    w("namespace HostFn")
    w("")
    w("def module : HostFn → Module")
    for m, f in fns:
        w(f"  | .{ident(f['name'])} => .{ident(m['name'])}")
    w("")
    w("/-- Wasm import field name (`export` in env.json). -/")
    w("def exportName : HostFn → String")
    for m, f in fns:
        w(f"  | .{ident(f['name'])} => {lean_str(f['export'])}")
    w("")
    w("/-- The Rust/env.json name of the host function. -/")
    w("def name : HostFn → String")
    for m, f in fns:
        w(f"  | .{ident(f['name'])} => {lean_str(f['name'])}")
    w("")
    w("/-- Argument names and types, in order. Every argument is an i64 at the wasm level. -/")
    w("def args : HostFn → List (String × ValTy)")
    for m, f in fns:
        a = ", ".join(f"({lean_str(x['name'])}, .{ident(x['type'])})" for x in f["args"])
        w(f"  | .{ident(f['name'])} => [{a}]")
    w("")
    w("def ret : HostFn → ValTy")
    for m, f in fns:
        w(f"  | .{ident(f['name'])} => .{ident(f['return'])}")
    w("")
    w("def minProto : HostFn → Option Nat")
    for m, f in fns:
        v = f.get("min_supported_protocol")
        w(f"  | .{ident(f['name'])} => {'none' if v is None else f'some {v}'}")
    w("")
    w("def maxProto : HostFn → Option Nat")
    for m, f in fns:
        v = f.get("max_supported_protocol")
        w(f"  | .{ident(f['name'])} => {'none' if v is None else f'some {v}'}")
    w("")
    w("def arity (f : HostFn) : Nat := f.args.length")
    w("")
    w("/-- HOST_FUNCTIONS order (src: soroban-env-host/src/vm/func_info.rs:131-140). -/")
    w("def all : Array HostFn := #[")
    w(",\n".join(f"  .{ident(f['name'])}" for _, f in fns))
    w("]")
    w("")
    w("/-- Resolve a wasm import `(module, field)` to a host function, as the wasmi")
    w("    Linker populated from HOST_FUNCTIONS does. -/")
    w("def resolve (modStr fieldStr : String) : Option HostFn :=")
    w("  match modStr, fieldStr with")
    for m, f in fns:
        w(f"  | {lean_str(m['export'])}, {lean_str(f['export'])} => some .{ident(f['name'])}")
    w("  | _, _ => none")
    w("")
    w("end HostFn")
    w("")
    w(f"/-- Number of host functions in env.json. -/")
    w(f"def hostFnCount : Nat := {len(fns)}")
    w("")
    w("end Soroban.Env")
    OUT.write_text("\n".join(o) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(fns)} host fns, {len(types)} types, {len(env['modules'])} modules")


if __name__ == "__main__":
    main()
