#!/usr/bin/env python3
"""Mainnet cost parameters (vendor/network/mainnet_settings.json, the JSON form of
mainnet_settings.xdr) as Lean literals: Proofs/MainnetBudget.lean. A kernel-checked
theorem there ties them to the decoded XDR settings bytes."""
import json, os
root = os.path.join(os.path.dirname(__file__), '..') + '/'
d = json.load(open(root + 'vendor/network/mainnet_settings.json'))
cpu = mem = None; cl = ml = None
for e in d['updated_entry']:
    k = list(e.keys())[0]
    if k == 'contract_cost_params_cpu_instructions': cpu = e[k]
    if k == 'contract_cost_params_memory_bytes': mem = e[k]
    if k == 'contract_compute_v0': cl = e[k]['tx_max_instructions']; ml = e[k]['tx_memory_limit']
def arr(ps): return '#[' + ', '.join(f'⟨.v0, {p["const_term"]}, {p["linear_term"]}⟩' for p in ps) + ']'
out = f'''/-
Mainnet cost parameters as literals (generated by tools/gen_budget.py from
vendor/network/mainnet_settings.json), and the proof that they are exactly what the
XDR settings bytes decode to.
-/
import Proofs.IncrementInputs

namespace Proofs
open Soroban

def mainnetCpuParams : Array Xdr.ContractCostParamEntry := {arr(cpu)}
def mainnetMemParams : Array Xdr.ContractCostParamEntry := {arr(mem)}
def mainnetCpuLimit : Nat := {cl}
def mainnetMemLimit : Nat := {ml}

def paramsKey (ps : Array Xdr.ContractCostParamEntry) : List (Int × Int) :=
  ps.toList.map fun p => (p.constTerm.toInt, p.linearTerm.toInt)

set_option maxRecDepth 100000 in
/-- The literals are the decoded mainnet settings. -/
theorem mainnet_params_eq :
    ((Xdr.decodeToEnd Xdr.rd_ConfigUpgradeSet mainnetSettings).toOption.bind NetConfig.ofUpgradeSet).map
      (fun n => (paramsKey n.cpu, paramsKey n.mem, n.cpuLimit, n.memLimit)) =
    some (paramsKey mainnetCpuParams, paramsKey mainnetMemParams, mainnetCpuLimit, mainnetMemLimit) := by
  decide +kernel

end Proofs
'''
open(root + 'Proofs/MainnetBudget.lean', 'w').write(out)
